package Allquestions;

public class Add {

	public void add (int a , int b) {
		
		int c = a+b;
		
		System.out.println(c);
		
	}
	
	public void add (int a , int b , int c) {
		
		int d = a+b+c;
		
		System.out.println(d);
	}
	
	public void add (double l , double m) {
		
		double e = l+m;
		
		System.out.println(e);
	}
}
